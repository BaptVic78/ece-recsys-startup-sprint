PACE_FACTOR = {"easy": 1.0, "long": 1.04, "tempo": 0.88, "intervals": 0.85}
SHARE = {"easy": 1.0, "tempo": 1.1, "intervals": 0.9}


def weekly_volume(profile, week):
    """Linear build-up from start to peak, with a cut-back every fourth week."""
    progress = week / (WEEKS - 1)
    km = profile["start_km"] + (profile["peak_km"] - profile["start_km"]) * progress
    long_km = profile["long_start"] + (profile["long_peak"] - profile["long_start"]) * progress
    if week % 4 == 3:
        km, long_km = km * 0.75, long_km * 0.7
    return km, long_km


def history(profile, rng):
    sessions = []
    for week in range(WEEKS):
        week_km, long_km = weekly_volume(profile, week)
        others = {day: role for day, role in profile["days"].items() if role != "long"}
        weights = {day: SHARE[role] for day, role in others.items()}
        rest_km = max(week_km - long_km, 5 * len(others))
        for day in range(7):
            role = profile["days"].get(day)
            if role is None or rng.random() < 0.07:  # rest day or a missed session
                continue
            km = long_km if role == "long" else rest_km * weights[day] / sum(weights.values())
            km = round(float(km * rng.uniform(0.9, 1.1)), 1)
            pace = profile["easy_pace"] * PACE_FACTOR[role] * rng.uniform(0.97, 1.03)
            days_ago = (WEEKS - week) * 7 - day
            sessions.append({"days_ago": int(days_ago), "km": km, "minutes": round(km * pace, 1), "type": role})
    return sorted(sessions, key=lambda s: -s["days_ago"])


def main():
    rng = np.random.default_rng(2026)
    profiles = []
    for profile in PROFILES:
        sessions = history(profile, rng)
        profiles.append({key: value for key, value in profile.items() if key not in ("days", "start_km", "peak_km",
                                                                                     "long_start", "long_peak")}
                        | {"sessions": sessions, "runs": len(sessions),
                           "total_km": round(sum(s["km"] for s in sessions), 1)})
    path = Path("demo/mock_profiles.json")
    path.write_text(json.dumps({"note": "Synthetic demo histories generated by marathon/mock_profiles.py; "
                                        "not real people.", "profiles": profiles}, indent=1) + "\n", encoding="utf-8")
    for profile in profiles:
        print(f"{profile['name']:<16} {profile['source']:<15} {profile['runs']:>3} runs {profile['total_km']:>6} km")


if __name__ == "__main__":
    main()
