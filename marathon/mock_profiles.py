"""Generate the five mock running histories used by the demo's "import from your running app" step.

These are synthetic, not real people: 12 weeks of marathon preparation per profile, with a
weekly structure typical of marathon training (a progressive Sunday long run, one or two faster
sessions, easy runs, a cut-back week every fourth week, a few missed days). Dates are stored as
days before the import, so the history always ends yesterday whatever day the demo runs.

    python -m marathon.mock_profiles     # writes demo/mock_profiles.json
"""

